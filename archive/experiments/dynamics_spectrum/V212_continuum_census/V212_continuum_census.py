#!/usr/bin/env python3
"""V212 - the continuum census: what symmetry the infrared of the implemented
module allows at its gapless points, and what the root forbids.

The cone programme (V118, V185-V187, V207, and the 33800-point search of
V132's class) closed negatively from inside: no conical node in the
automaton's own circuit class, and at every exactly-gapless point the tangent
velocity algebra is abelian with planar branches.  V212 answers the same
question at the level where it is decidable by algebra rather than by search -
what the SYMMETRY allows at each high-symmetry locus, measured on the
implemented module - and then measures the obstruction the root puts in the
way of the symmetric alternative.

T1 the locus census.  What protects a gapless point at momentum q against
   anisotropic Fermi velocities is the subgroup of the spatial point group that
   fixes q.  For every named locus of the implemented cell Brillouin zone
   (cl10.supercell.HIGH_SYM) V212 measures the little-group order, the Molien
   invariant counts, the gap of the implemented one-step matrix at the clock in
   force, the number of exactly-zero eigenphases, and the dispersion exponent
   along a generic ray.  The result is a trap with both jaws measured: the one
   locus where isotropy is FORCED (GAMMA, full cubic little group, one
   quadratic invariant) is exactly gapless but its touching is QUADRATIC, with
   a macroscopically degenerate zero-phase manifold - an isotropic linear
   crossing is not there; and every locus that does touch linearly (the M
   lines) has three quadratic invariants, so anisotropic velocities there are
   required by symmetry and no tuning removes them.

T2 the target comparison.  The same invariant census for the cubic group the
   automaton implements and for the icosahedral group built from the triangle
   presentation (cl10/config.yaml: continuum.icosahedral_generator_orders =
   (2,3,5)): both rings have a unique quadratic invariant, but the first
   anisotropic invariant sits at degree 4 for the cubic group and at degree 6
   for the icosahedral one - the order in |q|/Lambda at which a dispersion may
   depart from a rotational form.

T3 the obstruction.  The finite link group of the root is generated by the 10
   Clifford involutions: V212 measures its order and element-order spectrum.
   It is a 2-group, so it has no element of order 3 or 5, hence no icosahedral
   subgroup (order 60) and no binary icosahedral subgroup (order 120): the
   symmetry an icosahedral infrared would need is not a subgroup of the
   symmetry the root uses.

T4 what the root contains anyway.  The even Clifford algebra over three
   spatial generators IS the quaternion algebra (relation defects at machine
   zero), and the binary icosahedral units generated from the icosahedral
   presentation close to order 120 INSIDE that algebra, unitarily, with
   elements of orders 4, 6 and 10.  The missing symmetry is absent from the
   finite group and present in the algebra the module is built from: that is
   the distinction a continuum route has to exploit.

T5 the lattice test.  The group's own 5-fold axes give 6 axes / 12 directions
   in three physical dimensions, and the trace of an order-5 element is
   1 + 2 cos(2 pi/5) = the golden ratio, not an integer: a lattice symmetry is
   integral in every lattice basis, so no lattice in three dimensions carries
   this point group.  The cubic group passes the same test with zero
   non-integral traces.

Inputs: cl10/config.yaml (continuum.census_degrees,
continuum.icosahedral_generator_orders, the clock branch, tolerances).  Every
order, count, gap, exponent and trace below is measured.
"""
import json
import math
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, ROOT)
os.environ["CL10_BACKEND"] = "numpy"   # an algebraic census: pin the CPU core

import numpy as np

from cl10 import altcell as A
from cl10 import config as _config
from cl10 import continuum as K
from cl10 import supercell as SC

CFG = _config.CFG
CELL = A.cell((2, 2, 2))
STAGES = A.stages_baseline()
EPS_RAY = [1e-2, 3e-3, 1e-3, 3e-4, 1e-4]     # probe distances for the dispersion fit
GENERIC_RAY = (2.0, 1.0, 0.0)                # no symmetry axis, no special plane


def bloch(q):
    """The implemented one-step matrix at momentum q: the construction the
    committed spectra of V132, V203 and V207 are made of."""
    return A.bloch_cell(CELL, SC.sectors()[2], SC.G10, STAGES, q)


def phases(q):
    return np.sort(np.abs(np.angle(np.linalg.eigvals(bloch(q)))))


def dispersion(center, ray=GENERIC_RAY, eps=EPS_RAY):
    """The lowest eigenphase as a function of distance from `center` along
    `ray`, with the fitted power law (log-log slope and coefficient) and the
    linear-velocity diagnostic gap/momentum at the largest probe."""
    v = np.array(ray, float)
    v /= np.linalg.norm(v)
    c = np.array(center, float)
    gaps = [float(np.min(phases(tuple(c + e * v)))) for e in eps]
    good = [(e, g) for e, g in zip(eps, gaps) if g > 0]
    if len(good) >= 2:
        x = np.array([math.log(e) for e, _ in good])
        y = np.array([math.log(g) for _, g in good])
        slope, intercept = np.polyfit(x, y, 1)
        law = {"exponent": float(slope), "coefficient": float(math.exp(intercept)),
               "points": [[e, g] for e, g in good]}
    else:
        law = {"exponent": None, "coefficient": None,
               "points": [[e, g] for e, g in zip(eps, gaps)]}
    return {"gaps": gaps, "law": law,
            "phase_over_momentum_at_largest_probe": float(gaps[0] / eps[0])}


def trace_spectrum(elements, tol):
    tr = sorted({round(float(np.trace(m).real), 9) for m in elements})
    return tr, [t for t in tr if abs(t - round(t)) > tol]


def main():
    t0 = time.time()
    clock = float(CFG.angle.g10)
    branch = str(CFG.angle.branch)
    tol = float(CFG.tolerances.standard)

    # ------------------------------------------------- T1: the locus census
    loci = [(name, pts[0]) for name, pts in SC.HIGH_SYM.items()]
    t1 = K.locus_census(loci)
    for r in t1:
        q = np.array(r["q"], float)
        ph = phases(r["q"])
        r["gap"] = float(ph[0])
        r["zero_phases"] = int(np.sum(ph < tol))
        r["spectrum_size"] = int(ph.size)
        r["star_size"] = len(A.oh_star(tuple(q)))
        r["off_module"] = dispersion(r["q"])
    forced = [r["locus"] for r in t1 if r["isotropy_forced"]]
    gapless = [r["locus"] for r in t1 if r["gap"] < tol]
    byname = {r["locus"]: r for r in t1}

    # the gapless line through GAMMA and M: the ray joining them
    line_dir = tuple(np.array(byname["M"]["q"], float) / 2.0)
    line_gaps = [float(np.min(phases(tuple(e * x for x in line_dir))))
                 for e in (0.25, 0.5, 0.75, 1.0)]

    # -------------------------------------------- T2: cubic vs icosahedral
    ico = K.polyhedral_group()
    cubic = K.cubic_group()
    cubic_m, ico_m = K.molien_counts(cubic), K.molien_counts(ico["elements"])
    rings = {
        "cubic": {"order": len(cubic), "invariants": cubic_m,
                  "quadratic_invariants": cubic_m[1],
                  "first_anisotropic_degree": K.first_anisotropic_degree(cubic_m)},
        "icosahedral": {"order": ico["order"], "invariants": ico_m,
                        "quadratic_invariants": ico_m[1],
                        "first_anisotropic_degree": K.first_anisotropic_degree(ico_m),
                        "presentation": ico["orders"],
                        "generator_orders": ico["generator_orders"],
                        "product_order": ico["product_order"],
                        "element_orders": ico["element_orders"],
                        "presentation_trace_defect": ico["trace_defect"]},
        "so3_reference": K.so3_counts(),
    }

    # --------------------------------------------------- T3: the root's group
    rg = K.root_link_group()
    subgroup_possible = {str(k): (rg["order"] % k == 0
                                  and (k in rg["element_orders"] or k == 1))
                         for k in (3, 5, 60, 120)}

    # ------------------------------ T4: 2I inside the even Clifford algebra
    ev = K.clifford_even_3d()
    bp = K.binary_polyhedral(ico["generators"])
    mats, unitarity = K.embed_quaternions(bp["_qel"], ev)
    embedded_closure = len(K.closure(mats[:3], cap=512))

    # -------------------------------------- T5: the star and the lattice test
    axes = K.polyhedral_axes(ico["elements"], 5)
    tr5 = float(np.trace(ico["generators"][1]).real)
    tr_spec, nonint = trace_spectrum(ico["elements"], tol)
    _, cubic_nonint = trace_spectrum(cubic, tol)

    # --------------------------------------------------------- the checks
    checks, ok = [], True

    def chk(name, cond, detail):
        nonlocal ok
        checks.append({"name": name, "pass": bool(cond), "detail": detail})
        ok = ok and bool(cond)

    gam, mloc = byname["GAMMA"], byname["M"]
    chk("T1 isotropy is forced at exactly one locus, the zone centre",
        forced == ["GAMMA"] and gam["quadratic_invariants"] == 1,
        f"forced {forced}; GAMMA little group order {gam['little_group_order']}, "
        f"quadratic invariants {gam['quadratic_invariants']}")
    chk("T1 the isotropy-forced locus is gapless but its touching is quadratic, "
        "not linear",
        gam["gap"] < tol and gam["off_module"]["law"]["exponent"] is not None
        and abs(gam["off_module"]["law"]["exponent"] - 2.0) < 0.25,
        f"GAMMA gap {gam['gap']:.1e} with {gam['zero_phases']} of "
        f"{gam['spectrum_size']} eigenphases zero; fitted dispersion exponent "
        f"{gam['off_module']['law']['exponent']:.3f} (coefficient "
        f"{gam['off_module']['law']['coefficient']:.3e}); gap/momentum at the "
        f"largest probe {gam['off_module']['phase_over_momentum_at_largest_probe']:.2e}")
    chk("T1 the linear-touching loci force anisotropy",
        mloc["gap"] < tol and mloc["quadratic_invariants"] > 1
        and mloc["off_module"]["law"]["exponent"] is not None
        and abs(mloc["off_module"]["law"]["exponent"] - 1.0) < 0.3,
        f"M gap {mloc['gap']:.1e}, quadratic invariants "
        f"{mloc['quadratic_invariants']}, little group order "
        f"{mloc['little_group_order']}, dispersion exponent "
        f"{mloc['off_module']['law']['exponent']:.3f}")
    chk("T1 the GAMMA-M line is exactly gapless",
        max(line_gaps) < tol,
        f"gaps along the GAMMA-M segment {['%.1e' % g for g in line_gaps]}")
    chk("T2 the icosahedral ring is strictly closer to rotational invariance",
        rings["icosahedral"]["first_anisotropic_degree"]
        > rings["cubic"]["first_anisotropic_degree"]
        and rings["icosahedral"]["quadratic_invariants"] == 1,
        f"cubic {rings['cubic']['first_anisotropic_degree']} (counts {cubic_m}), "
        f"icosahedral {rings['icosahedral']['first_anisotropic_degree']} "
        f"(counts {ico_m})")
    chk("T3 the root link group carries no element of order 3 or 5",
        rg["is_2_group"] and 3 not in rg["element_orders"]
        and 5 not in rg["element_orders"],
        f"order {rg['order']} from {rg['generators']} involutions, element "
        f"orders {rg['element_orders']}, subgroup test {subgroup_possible}")
    chk("T4 the binary icosahedral units close inside the even Clifford algebra",
        bp["order"] == 2 * ico["order"] and embedded_closure == bp["order"]
        and ev["square_to_minus_one"] < float(CFG.tolerances.strict)
        and ev["quaternion_products"] < float(CFG.tolerances.strict)
        and unitarity < tol,
        f"|2I| = {bp['order']} = 2 x {ico['order']}; embedded closure "
        f"{embedded_closure}; Clifford relation defects "
        f"{ev['square_to_minus_one']:.1e} / {ev['quaternion_products']:.1e}; "
        f"unitarity {unitarity:.1e}")
    chk("T4 the algebra carries orders the group does not",
        not set(bp["element_orders"]).issubset(set(rg["element_orders"])),
        f"algebra orders {bp['element_orders']} vs group orders "
        f"{rg['element_orders']}")
    chk("T5 no lattice in three dimensions carries the icosahedral point group",
        bool(nonint) and abs(tr5 - round(tr5)) > tol and not cubic_nonint,
        f"tr of an order-5 element {tr5:.9f}; non-integral traces "
        f"{len(nonint)} of {len(tr_spec)} (icosahedral), "
        f"{len(cubic_nonint)} (cubic)")

    verdict = {
        "id": os.path.basename(HERE),
        "tier": 4,
        "property": "symmetry census of the continuum question: little groups, "
                    "Molien invariant counts, eigenphase counts and measured "
                    "dispersion exponents at every high-symmetry locus of the "
                    "implemented cell Brillouin zone at the clock in force; the "
                    "cubic-versus-icosahedral invariant rings; the order and "
                    "element-order spectrum of the root's finite link group; "
                    "the binary icosahedral units inside the even Clifford "
                    "algebra; and the crystallographic trace test",
        "residual": True,
        "pass": bool(ok),
        "status": (
            f"CONTINUUM CENSUS at the {branch} clock g = {clock:.6f}. "
            "(T1) " + "; ".join(
                f"{r['locus']}: |little group| {r['little_group_order']}, "
                f"{r['quadratic_invariants']} quadratic invariants, first "
                f"anisotropic degree {r['first_anisotropic_degree']}, gap "
                f"{r['gap']:.1e} ({r['zero_phases']}/{r['spectrum_size']} "
                f"eigenphases zero), dispersion exponent "
                f"{r['off_module']['law']['exponent'] if r['off_module']['law']['exponent'] is not None else 'n/a (gapless along the probed ray)'}"
                for r in t1)
            + f". Isotropy is forced at exactly one locus, {forced}, and it is "
              f"gapless - but its touching is QUADRATIC (exponent "
              f"{gam['off_module']['law']['exponent']:.2f}, "
              f"{gam['zero_phases']} zero eigenphases), so the symmetry-forced "
              f"isotropic point carries no linear velocity: gap/momentum there "
              f"is {gam['off_module']['phase_over_momentum_at_largest_probe']:.1e} "
              f"and falling. The loci that do touch linearly (M, exponent "
              f"{mloc['off_module']['law']['exponent']:.2f}, exactly gapless, "
              f"and the whole GAMMA-M segment: max gap "
              f"{max(line_gaps):.1e}) have "
              f"{mloc['quadratic_invariants']} quadratic invariants, so "
              f"anisotropic Fermi velocities there are required by symmetry, "
              f"not by tuning: both jaws of the trap are measured. "
              f"(T2) the cubic group (order {rings['cubic']['order']}) has its "
              f"first anisotropic invariant at degree "
              f"{rings['cubic']['first_anisotropic_degree']}; the icosahedral "
              f"group built from the {rings['icosahedral']['presentation']} "
              f"presentation (order {rings['icosahedral']['order']}, generator "
              f"orders {rings['icosahedral']['generator_orders']}, product "
              f"order {rings['icosahedral']['product_order']}) has one quadratic "
              f"invariant and its first anisotropic invariant at degree "
              f"{rings['icosahedral']['first_anisotropic_degree']}: the "
              f"departure from rotational form is pushed two orders in "
              f"|q|/Lambda. (T3) the finite link group generated by the "
              f"{rg['generators']} Clifford involutions has order {rg['order']} "
              f"and element orders {rg['element_orders']}: a 2-group, so no "
              f"icosahedral (60) and no binary icosahedral (120) subgroup "
              f"(divisibility/element-order test {subgroup_possible}). "
              f"(T4) the even Clifford algebra on three spatial generators is "
              f"the quaternion algebra (relation defects "
              f"{ev['square_to_minus_one']:.1e} / {ev['quaternion_products']:.1e}) "
              f"and carries the binary icosahedral units: |2I| = {bp['order']}, "
              f"element orders {bp['element_orders']}, unitary to "
              f"{unitarity:.1e}, closing to {embedded_closure} inside the "
              f"{2 ** 5}-dimensional module. (T5) the group's own 5-fold axes "
              f"give {len(axes)} axes / {2 * len(axes)} directions; the trace of "
              f"an order-5 element is {tr5:.9f} = 1 + 2 cos(2 pi/5), "
              f"non-integral, {len(nonint)} of {len(tr_spec)} traces "
              f"non-integral while the cubic group has none: no lattice in "
              f"three dimensions carries this point group."),
        "data": {"clock_branch": branch, "g10": clock,
                 "loci": t1, "forced_loci": forced, "gapless_loci": gapless,
                 "gamma_m_line": {"direction": list(line_dir), "gaps": line_gaps},
                 "rings": rings, "root_group": rg,
                 "subgroup_possible": subgroup_possible,
                 "clifford_quaternion_defects": {
                     "square_to_minus_one": ev["square_to_minus_one"],
                     "quaternion_products": ev["quaternion_products"]},
                 "binary_icosahedral": {"order": bp["order"],
                                        "element_orders": bp["element_orders"],
                                        "unitarity_defect": unitarity,
                                        "embedded_closure": embedded_closure},
                 "star": {"axes": axes, "directions": 2 * len(axes),
                          "order5_trace": tr5,
                          "icosahedral_traces": tr_spec,
                          "icosahedral_nonintegral_traces": len(nonint),
                          "cubic_nonintegral_traces": len(cubic_nonint)},
                 "checks": checks},
        "wall_time": round(time.time() - t0, 3),
    }
    out = os.path.join(HERE, "results")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "v212_continuum_census.json"), "w") as f:
        json.dump(verdict, f, indent=2, ensure_ascii=False)

    print("=" * 68)
    print("V212 - the continuum census")
    print("=" * 68)
    for r in t1:
        law = r["off_module"]["law"]
        print(f"  {r['locus']:6s} |little| {r['little_group_order']:3d}  "
              f"quad {r['quadratic_invariants']}  forced "
              f"{str(r['isotropy_forced']):5s}  aniso deg "
              f"{r['first_anisotropic_degree']}  gap {r['gap']:.1e}  "
              f"zero ph {r['zero_phases']:3d}/{r['spectrum_size']}  "
              f"exponent {law['exponent'] if law['exponent'] is not None else '--'}")
    print(f"  cubic ring {cubic_m} (first aniso "
          f"{rings['cubic']['first_anisotropic_degree']}) | icosahedral ring "
          f"{ico_m} (first aniso {rings['icosahedral']['first_anisotropic_degree']})")
    print(f"  root link group order {rg['order']} element orders "
          f"{rg['element_orders']}")
    print(f"  |2I| = {bp['order']} in Cl^0(3), orders {bp['element_orders']}, "
          f"embedded closure {embedded_closure}")
    print(f"  star {len(axes)} axes / {2 * len(axes)} directions; tr(order 5) "
          f"= {tr5:.9f}; non-integral traces {len(nonint)}/{len(tr_spec)} "
          f"(cubic {len(cubic_nonint)})")
    for c in checks:
        print(f"  [{'ok' if c['pass'] else 'FAIL'}] {c['name']}")
        print(f"        {c['detail']}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
