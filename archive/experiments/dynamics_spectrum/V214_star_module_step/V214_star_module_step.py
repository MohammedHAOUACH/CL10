#!/usr/bin/env python3
"""V214 - the icosahedral-module step: what the module change costs, and what
it fixes.

V212 and V213 closed the implemented shift module.  Isotropy is forced at
exactly one locus of its Brillouin zone and the touching there is quadratic;
the loci that touch linearly have their anisotropy forced by symmetry; and the
tangent anisotropy is marginal at the node (p = -0.0001 read from a radius
ladder, 0.0000 from a block ladder with the window AND the probe rescaled), so
coarse-graining inside the cubic module never produces a rotational infrared.
The root's own algebra points elsewhere: the finite link group generated by the
ten Clifford involutions is a 2-group (order 2048, element orders {1, 2, 4}) so
it contains no icosahedral or binary icosahedral subgroup, yet the even
Clifford algebra over three spatial generators IS the quaternion algebra and
carries the binary icosahedral units (|2I| = 120, element orders
{1, 2, 3, 4, 5, 6, 10}, closing to 120 inside the 32-dimensional module).  The
symmetry the continuum needs is absent from the group and present in the
algebra.

So the module, not the internal sector, is what has to change.  The star module
(cl10/starcell.py) keeps the automaton exactly as it is - the same staggered
matching stages, the same committed internal map on the 16 sector, the same
clock - and replaces the three cubic bond directions with the six independent
axes of the icosahedral star.  A rank-6 module is the image of Z^6 under the
physical projection, so this is a periodic construction on Z^6 with Bloch
phases exp(i q . v_i), not an approximation of a quasilattice.

T1 the module's geometry and the price of the change, measured exactly
   (cl10/continuum.py, rational arithmetic): the six generators and their
   norms (the Lieb-Robinson radius per step), the rank of the module (6) and
   its relation lattice (6, exactly the pairs of opposites), the density
   witness (the shortest nonzero module displacement falls with the word bound:
   1.07, 0.45, 0.45, 0.25, 0.25 for bounds 1..5), and the word cost of the
   displacements the implemented engine hops on - the cubic axis x is NOT in the
   module (its unique rational representation is half-integral), x + y is, at
   two steps, and the shortest rational-direction hop costs eight steps.
   Also what the star buys: six equiangular lines at 1/sqrt 5 (the measured
   icosahedral group's own axes give the same spectrum), a vanishing
   fourth-moment defect where the cubic axes have 0.400.

T2 the growth: the number of distinct module points within k steps against the
   physical radius - the rank-6 module grows like radius^6 in three physical
   dimensions, which is the counting form of the same aperiodity V212 sees in
   the trace test.

T3 the step's invariants: the committed internal map (unitarity, determinant)
   and the module step (unitarity, determinant), for both stagger conventions
   (phase-major as `supercell.STAGES` alternates, and block-major) - the
   stagger is a choice of construction, so both are reported rather than one
   being assumed.

T4 the mirror Z2: the relation the committed cubic step satisfies between
   M(-q) and M(q) conjugated by the cell reflection is first MEASURED on the
   cubic step (the candidate that holds is selected by the data, not asserted),
   then re-tested on the star step, whose star is inversion-closed (the twelve
   signed directions are six axes).

Inputs: cl10/config.yaml (angle branch and clock, continuum.census_degrees,
tolerances) and the committed internal map `supercell.sectors()[2]`.  Nothing
about the star is hardcoded: it comes from `continuum.icosahedral_generator_orders`.
"""
