def R(phi, sign, D):
    """exp(i sign phi D) - exact because D^2 = I."""
    return math.cos(phi) * I16 + 1j * sign * math.sin(phi) * D


def layer_block(even, j, phi):
    """The bond layer of one stage as an 8x8 block matrix of 16x16 blocks,
    written as three q-independent pieces: (diag, e^{+iq} piece, e^{-iq}
    piece).  Axis j carries the internal rotation generated by SIG[j]."""
    c, s = math.cos(G10), math.sin(G10)
    diag = np.zeros((8, 8, 16, 16), dtype=complex)
    plus = np.zeros((8, 8, 16, 16), dtype=complex)
    minus = np.zeros((8, 8, 16, 16), dtype=complex)
    bit = 1 << j
    for e in range(8):
        diag[e, e] = c * I16
    for e in range(8):
        if (e & bit) == (0 if even else bit):
            o = e ^ bit
            sign = 1 if (e & bit) == 0 else -1
            hop = -1j * s * R(phi[j], sign, SIG[j])
            hopr = -1j * s * R(phi[j], -sign, SIG[j])
            if even:
                diag[e, o] = hop
                diag[o, e] = hopr
            else:
                plus[e, o] = hop          # (e & bit) == bit here
                minus[o, e] = hopr
    return diag, plus, minus


def to_full(A):
    return A.transpose(0, 2, 1, 3).reshape(128, 128)


class Step:
    """M(q) = W(q) . sum_sigma c_sigma(q) P_sigma for one bond choice."""

    def __init__(self, phi):
        Ui = to_full(np.array([[U16 if e == f else np.zeros((16, 16))
                                for f in range(8)] for e in range(8)]))
        # per stage: list of (axis, hop sign, matrix); axis None -> no phase
        stages = []
        for even, j in ORDER:
            diag, plus, minus = layer_block(even, j, phi)
            if even:
                stages.append([(None, 0, to_full(diag) @ Ui)])
            else:
                stages.append([(None, 0, to_full(diag) @ Ui),
                               (j, 1, to_full(plus) @ Ui),
                               (j, -1, to_full(minus) @ Ui)])
        terms = [({}, np.eye(128, dtype=complex))]
        for st in stages:
            new = []
            for t in terms:
                for axis, sgn, mat in st:
                    sig = dict(t[0])
                    if axis is not None:
                        sig[axis] = sig.get(axis, 0) + sgn
                    new.append((sig, mat @ t[1]))
            terms = new
        self.sig = np.array([[t[0].get(0, 0), t[0].get(1, 0), t[0].get(2, 0)]
                             for t in terms])
        self.P = np.array([t[1] for t in terms])
        self.dcache = {}

    def M(self, q, w, th):
        ph = w * sum(1.0 - math.cos(qj) for qj in q)
        key = round(th, 12)
        d = self.dcache.get(key)
        if d is None:
            d = self.dcache[key] = _lam @ (math.cos(th) * XCOEF
                                           + math.sin(th) * YCOEF)
        wd = np.exp(-1j * ph * np.tile(d, 8))
        coeffs = np.exp(1j * (self.sig @ np.asarray(q)))
        X = np.tensordot(coeffs, self.P, axes=([0], [0]))
        return wd[:, None] * X


def slow_M(q, w, th, phi):
    """Reference implementation (stage-by-stage block einsum), as in V120."""
    def lb(even, j, qq):
        c, s = math.cos(G10), math.sin(G10)
        S = np.zeros((8, 8, 16, 16), dtype=complex)
        bit = 1 << j
        for e in range(8):
            S[e, e] = c * I16
        for e in range(8):
            if (e & bit) == (0 if even else bit):
                o = e ^ bit
                ph = 1.0 if even else (np.exp(1j * qq) if (e & bit)
                                       else np.exp(-1j * qq))
                sign = 1 if (e & bit) == 0 else -1
                S[e, o] = -1j * s * ph * R(phi[j], sign, SIG[j])
                S[o, e] = -1j * s * np.conj(ph) * R(phi[j], -sign, SIG[j])
        return S

    def bm(A, Bm):
        return np.einsum("ijab,jkbc->ikac", A, Bm, optimize=True)

    X = np.zeros((8, 8, 16, 16), dtype=complex)
    for e in range(8):
        X[e, e] = I16
    Ui = np.zeros((8, 8, 16, 16), dtype=complex)
    for e in range(8):
        Ui[e, e] = U16
    for even, j in ORDER:
        X = bm(bm(lb(even, j, q[j]), Ui), X)
    ph = w * sum(1.0 - math.cos(qj) for qj in q)
    d = _lam @ (math.cos(th) * XCOEF + math.sin(th) * YCOEF)
    Wd = np.zeros((8, 8, 16, 16), dtype=complex)
    for e in range(8):
        Wd[e, e] = np.diag(np.exp(-1j * ph * d))
    return to_full(bm(Wd, X))


def tri(st, q, m=3, w=0.0, th=0.0):
    a = np.sort(np.abs(np.angle(np.linalg.eigvals(st.M(q, w, th)))))
    return a[:m]


def tangent(st, q, m=3, h=1e-5, w=0.0, th=0.0):
    ev, V = np.linalg.eig(st.M(q, w, th))
    sel = np.argsort(np.abs(np.angle(ev)))[:m]
    Q, _ = np.linalg.qr(V[:, sel])
    S = []
    for j in range(3):
        qp, qm = list(q), list(q)
        qp[j] += h
        qm[j] -= h
        D = (st.M(tuple(qp), w, th) - st.M(tuple(qm), w, th)) / (2 * h)
        S.append(1j * (Q.conj().T @ D @ Q))
    nrm = [float(np.linalg.norm(s)) for s in S]
    mean2 = sum(n * n for n in nrm) / 3.0
    comm = max(float(np.linalg.norm(S[a] @ S[b] - S[b] @ S[a]))
               for a, b in ((0, 1), (1, 2), (2, 0)))
    comm_ratio = comm / mean2 if mean2 > 0 else 0.0
    c2 = sum(float(np.linalg.norm(s @ s)) for s in S) / 3.0
    defect = 0.0
    if c2 > 0:
        for a, b in ((0, 1), (1, 2), (2, 0)):
            defect = max(defect, float(np.linalg.norm(
                S[a] @ S[b] + S[b] @ S[a])) / (2 * c2))
        for s in S:
            defect = max(defect, abs(float(np.linalg.norm(s @ s)) - c2) / c2)
    return S, comm_ratio, defect


def sphere(n=6):
    out = []
    for i in range(-n, n + 1):
        for j in range(-n, n + 1):
            for k in range(-n, n + 1):
                r = math.sqrt(i * i + j * j + k * k)
                if r > 0:
                    out.append((i / r, j / r, k / r))
    return out


def speeds(S, dirs):
    spd = []
    for kd in dirs:
        Ax = kd[0] * S[0] + kd[1] * S[1] + kd[2] * S[2]
        spd.extend(sorted(abs(x) for x in np.linalg.eigvalsh(Ax)))
    spd = np.array(spd)
    nz = spd[spd > 1e-6]
    if not nz.size:
        return None, 0.0, 0.0, int((spd < 1e-6).sum()), len(spd)
    return (float((nz.max() - nz.min()) / (nz.max() + nz.min())),
            float(nz.min()), float(nz.max()),
            int((spd < 1e-6).sum()), len(spd))


def tune(phi, q, m=3, grid=18, wmax=3.0):
    """Golden-section refinement of (w, theta) minimising the top level of the
    m-dimensional gapless multiplet at fixed bond phi."""
    gr = (math.sqrt(5.0) - 1.0) / 2.0
    st = Step(phi)
    best = (9.0, None)
    for it in range(grid):
        th = 2 * math.pi * it / grid
        for w in np.linspace(0.0, wmax, 19):
            a = tri(st, q, m, float(w), th)
            if a[m - 1] < best[0]:
                best = (a[m - 1], (float(w), th))
    w, th = best[1]
    for _ in range(6):
        for var in ("w", "th"):
            lo, hi = (w - 0.1, w + 0.1) if var == "w" else (th - 0.2, th + 0.2)

            def f(x):
                ww, tt = (x, th) if var == "w" else (w, x)
                return tri(st, q, m, ww, tt)[m - 1]
            c1, c2 = hi - gr * (hi - lo), lo + gr * (hi - lo)
            f1, f2 = f(c1), f(c2)
            for _ in range(25):
                if f1 < f2:
                    hi, c2, f2 = c2, c1, f1
                    c1 = hi - gr * (hi - lo)
                    f1 = f(c1)
                else:
                    lo, c1, f1 = c1, c2, f2
                    c2 = lo + gr * (hi - lo)
                    f2 = f(c2)
            if var == "w":
                w = 0.5 * (lo + hi)
            else:
                th = 0.5 * (lo + hi)
    a = tri(st, q, m, w, th)
    return st, w, th, float(a[0]), float(a[m - 1]), \
        float(a[m - 1] - a[0])


def fourier_support():
    """Radius-1 locality: M(q) must be a trigonometric polynomial of degree
    1 in every q_j - the causal-radius-1 (Lieb-Robinson) statement.  Tested
    with a 5-point DFT along each axis: modes 2 and 3 must vanish.  A 3-point
    DFT aliases degree 1 with degree 2 and cannot test this."""
    err = 0.0
    phi = (0.3, 0.6, 0.9)
    for j in range(3):
        mats = []
        for k in range(5):
            q = [0.61, -1.13, 2.27]
            q[j] = 2 * math.pi * k / 5
            mats.append(slow_M(tuple(q), 0.7, 0.4, phi))
        for n in (2, 3):
            F = sum(mats[k] * np.exp(-2j * math.pi * n * k / 5)
                    for k in range(5)) / 5
            err = max(err, float(np.abs(F).max()))
    return err


