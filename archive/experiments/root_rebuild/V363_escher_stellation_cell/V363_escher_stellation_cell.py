def _oh():
    gens = [np.array([[0, 1, 0], [1, 0, 0], [0, 0, 1]]),
            np.array([[0, 1, 0], [0, 0, 1], [1, 0, 0]]),
            np.array([[0, 0, -1], [1, 0, 0], [0, -1, 0]]),
            -np.eye(3, dtype=int)]
    I3 = np.eye(3, dtype=int)
    G, seen, fr = [I3], {tuple(I3.ravel())}, [I3]
    while fr:
        nf = []
        for M in fr:
            for Hh in gens:
                MH = M @ Hh
                k = tuple(MH.ravel())
                if k not in seen:
                    seen.add(k)
                    G.append(MH)
                    nf.append(MH)
        fr = nf
    return G


