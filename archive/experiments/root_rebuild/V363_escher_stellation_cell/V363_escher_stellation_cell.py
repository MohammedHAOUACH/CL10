def solid_vol_H():
    def tet(a, b, c):
        return (Fraction(a[0]) * (b[1] * c[2] - b[2] * c[1]) -
                Fraction(a[1]) * (b[0] * c[2] - b[2] * c[0]) +
                Fraction(a[2]) * (b[0] * c[1] - b[1] * c[0])) / 6
    volH = Fraction(0)
    for d in NORMALS:
        rh = FACES[d]
        if _dot(_cross(_sub(rh[1], rh[0]), _sub(rh[2], rh[0])), d) < 0:
            fan = [(rh[0], rh[2], rh[1]), (rh[0], rh[3], rh[2])]
        else:
            fan = [(rh[0], rh[1], rh[2]), (rh[0], rh[2], rh[3])]
        for a, b, c in fan:
            volH += tet(a, b, c)
    return volH


def solid_vol_pyramid(eta):
    """EXACT Fractions volume of ONE stellation pyramid of relative
    height eta (booked (4/3) eta, linear - base fixed): the d-face pyramid apex (1+eta) d
    over the cyclic base rhombus, tetrahedralized from apex."""
    tot = Fraction(0)
    for d in NORMALS:
        r = FACES[d]
        ap = tuple((1 + eta) * d[i] for i in range(3))
        for tri in [(r[0], r[1], r[2]), (r[0], r[2], r[3])]:
            u, v, w = _sub(tri[0], ap), _sub(tri[1], ap), \
                _sub(tri[2], ap)
            det = (Fraction(u[0]) * (v[1] * w[2] - v[2] * w[1]) -
                   Fraction(u[1]) * (v[0] * w[2] - v[2] * w[0]) +
                   Fraction(u[2]) * (v[0] * w[1] - v[1] * w[0])) / 6
            tot += det if det >= 0 else -det
    return tot / 12


