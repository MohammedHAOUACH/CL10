def _scale_int(vec):
    """multiply a Fraction vector by the lcm of denominators (>0)."""
    from math import gcd
    den = 1
    for x in vec:
        f = Fraction(x)
        den = den * f.denominator // gcd(den, f.denominator)
    return tuple(int(x * den) for x in vec)


def _cones(d, apex, ref):
    """facet half-space data (n, sgn, rhs) of the cone over the cyclic
    rhombus FACES[d] with apex 'apex': interior side is
    (n . x - rhs) * sgn > 0 with rhs = n . apex (the plane passes
    through the APEX - for a non-zero apex the raw n . x comparison is
    meaningless, the booked bug). 'ref' must lie strictly inside the
    cone segment (never beyond the apex across the cap)."""
    rh = FACES[d]
    ns = []
    for i in range(4):
        v1 = _sub(rh[i], apex)
        v2 = _sub(rh[(i + 1) % 4], apex)
        n = _scale_int(_cross(v1, v2))
        rhs = sum(Fraction(n[k]) * apex[k] for k in range(3))
        s = (sum(Fraction(ref[k]) * n[k] for k in range(3)) - rhs)
        sgn = 1 if s > 0 else -1
        assert rhs.denominator == 1
        ns.append((n, sgn, int(rhs)))
    return ns


