r"""V225 - the icosahedral star cell with a Clifford bond layer: what the
$2I$-covariant step gives at the zone centre.

The continuum programme measured why the cubic module has no rotational
infrared.  V212: isotropy is forced at exactly one locus, whose touching is
quadratic, while every linear touching has its anisotropy forced by its little
group.  V213: the tangent anisotropy is marginal (exponent $-0.0001$), so coarse
graining never removes it.  V215/V216: at every gapless point of the cubic and
of the star module the tangent generators vanish or the touching is not linear;
the Clifford test $\{S_a,S_b\} = 2\delta_{ab}$ fails by $2.000$ at the star's
zone centre and by $0.444$ at the cubic M node.  V219/V220: the star's own
gapless lines have degree-2 anisotropy and no charge, and a symmetry-respecting
mass opens them.  `supercell.bond_product` names the structural cause in its own
docstring: the committed step is $P(q)\otimes U^{n_s}$, transport and internal
layer factorized, and a factorized step cannot carry a non-Abelian tangent
algebra on a momentum-degenerate subspace.

`cl10/spincell` changes the module's *bond layer* instead of its internal
sector: the coin is the twelve directed directions of the icosahedral star and
the operator a hop carries is $U_d = -\hat v_d\cdot\vec\sigma$ -- Hermitian, an
involution (the root's link group is generated by involutions), a vector under
the binary icosahedral group, with $U_{-d} = -U_d$.  The clock and the internal
map stay committed; the internal map rides the block layer.

What is measured, in order:

T1 exactness of the covariance, the geometry of the cell, and the equivariant
   census at the node's little group: $D(R)U_dD(R)^\dagger = U_{\sigma_R(d)}$
   over all 120 lifts; the six axes as six equiangular lines with isotropic
   fourth moment; invariance of the step under $2I$ at the zone centre and the
   *failure* of inversion; and $\dim\mathrm{Hom}_{2I}(D, D\otimes\mathrm{Sym}^n
   V_3)$ for $n \le 8$, which forces the linear term and pushes the first
   anisotropy out to degree 5 (the cubic module's point group puts it at 4).
T2 the node arithmetic: the zone-centre gap as a function of the bond
   assignment, the number of block layers, and the power of the internal map
   that rides each layer.  With the Clifford layer the kinetic phases at the
   zone centre are pinned to $\{0,\pi\}$ independently of the clock, so the
   node closes exactly when the internal map's phase there is $0$ or $\pi$ --
   the map has order 8, measured -- i.e. exponent $0$ or $4$ mod 8.  The
   scalar assignment (no spin, the old factorized kinematics) is in the same
   table as the control that is gapless but has no velocity.
T3 the gap subspace and its $2I$ content by the character projector, built from
   the group rather than from a table, together with an orthonormal basis of
   each irrep's range.
T4 the tangent algebra on the gap subspace and on each irrep piece: the norms
   of the three generators, their off-diagonal anticommutators, their
   commutators, and -- the statement isotropy actually needs -- the *spectrum*
   of velocities of each generator, which must not depend on the direction.
   The squares of the generators are reported as what they are: on the spinor
   piece the speed is a single number, while the operators are not normal,
   because the internal sector is not a spectator for the tangent action.
T5 the dispersion, tracked through the gap subspace rather than through the
   global minimum gap (which wanders into other bands): at each of twenty
   directions the exponent of both the inner and the outer edge of the gap
   subspace's phase spread, and the velocities they imply.  Alongside, the
   number of bands sitting at phase zero to machine precision on the ray is
   counted: a ray that carries such pinned bands lies in the gapless set itself,
   and is reported as such instead of being fitted.
T6 the controls: the scalar bond assignment (no spin) and the quaternionic
   ("vector") assignment, measured in the same instruments.

Nothing here claims the cell is the physical one.  It claims the step is exactly
$2I$-covariant, that the node exists on it, that the touching is linear with a
direction-independent velocity spectrum in the directions that are not themselves
gapless, how many bands stay pinned at zero where they are, and how much of the
Clifford identity survives -- measured, not argued.
"""
