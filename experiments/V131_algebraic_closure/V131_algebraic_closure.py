I32 = np.eye(32, dtype=np.complex128)


def U_ordered(order, g):
    """The internal step at angle g for a given ordering of the 45 factors."""
    U = I32.copy()
    c, s = math.cos(g), math.sin(g)
    for T in order:
        U = U @ (c * I32 - 1j * s * T)
    return U


def order_err(U, Nmax=64):
    """The best exact order <= Nmax: (N, err)."""
    best = (0, 9.9)
    for N in range(1, Nmax + 1):
        e = float(np.abs(np.linalg.matrix_power(U, N) - I32).max())
        if e < best[1]:
            best = (N, e)
        if e < 1e-9:
            break
    return best


def main():
    t0 = time.time()
