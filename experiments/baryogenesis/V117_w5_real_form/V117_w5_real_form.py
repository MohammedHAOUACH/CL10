# ---------------------------------------------------------------------------
# the Frobenius-Schur test for a set of Clifford generators
# ---------------------------------------------------------------------------
def fs_indicator(h, tol=1e-9):
    """Type of the module generated by ``h``: the antilinear intertwiner
    ``J = Q K`` with ``J h J^-1 = h`` for every generator, and ``J^2 = Q Qbar``.

    Returns ``(type, J2)`` with type in {real, quaternionic, complex}.
    """
    n = h[0].shape[0]
    In = np.eye(n, dtype=complex)
    Mat = np.vstack([np.kron(A.T, In) - np.kron(In, np.conj(A)) for A in h])
    _, s, vt = np.linalg.svd(Mat, full_matrices=False)
    null = vt[s < tol]
    if null.shape[0] == 0:
        return "complex", None
    C = null[0].reshape(n, n)
    if np.linalg.matrix_rank(C) < n:
        return "complex", None
    U, _, Vh = np.linalg.svd(C)
    Q = U @ Vh                                    # unitary representative
    M = Q @ np.conj(Q)                            # J^2
    c = (np.trace(M) / n).real
    if np.abs(M - c * In).max() > 1e-6:
        return "indeterminate", c
    return ("real" if c > 0 else "quaternionic"), c


def conj_closed(U, tol=1e-12):
    """Exact test that spec(U) is closed under conjugation: the characteristic
    polynomial has real coefficients (branch-cut free, unlike sorted phases)."""
    c = np.poly(np.linalg.eigvals(U))
    return float(np.abs(np.imag(c)).max() / np.abs(c).max())


