def mul(s1, s2):
    """Product of signed sorted monomials (sign, (a1<...<ak))."""
    sign = s1[0] * s2[0]
    out = list(s1[1])
    for a in s2[1]:
        idx = next((i for i, x in enumerate(out) if x >= a), len(out))
        if idx < len(out) and out[idx] == a:
            sign *= (-1) ** (len(out) - idx - 1)
            out.pop(idx)
        else:
            sign *= (-1) ** (len(out) - idx)
            out.insert(idx, a)
    return (sign, tuple(out))


def invof(a):
    k = len(a[1])
    return (a[0] * (-1) ** (k * (k - 1) // 2), a[1])


BIFLECTIONS = [(1, (a, b)) for a in range(10) for b in range(a + 1, 10)]


def build_group():
    G = {(1, ()): None}
