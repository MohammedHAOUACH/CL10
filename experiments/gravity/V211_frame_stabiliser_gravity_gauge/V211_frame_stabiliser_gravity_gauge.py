def flat(ms):
    return np.array([m.ravel() for m in ms])


def in_span(W, V):
    """max residual of the rows of W in the row-span of V"""
    if len(W) == 0:
        return 0.0
    if len(V) == 0:
        return float(np.abs(W).max())
    c = np.linalg.lstsq(np.array(V).T, np.array(W).T, rcond=None)[0]
    return float(np.abs(np.array(W) - c.T @ np.array(V)).max())


def closure(ms):
    """(rank, closure residual) of a set of matrices under the commutator"""
    W = [(ms[i] @ ms[j] - ms[j] @ ms[i]).ravel()
         for i, j in itertools.combinations(range(len(ms)), 2)]
    return int(np.linalg.matrix_rank(flat(ms))), in_span(W, flat(ms))


def kernel_basis(A):
    """(orthonormal basis of the null space of A, rank of A)"""
    U, sv, Vh = np.linalg.svd(np.array(A), full_matrices=True)
    rk = int((sv > 1e-9 * sv[0]).sum()) if len(sv) else 0
    return Vh[rk:], rk


