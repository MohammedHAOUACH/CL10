def dark_matter():
    """The exact kink $u = \\sqrt{2}\\,\\mathrm{sech}\\,x$ of the cubic wave
    $u'' = u - u^3$: the ODE residual, the energy, the localisation, the
    neutrality.  It is a **planar domain wall** — the energy is per unit area
    and the total energy is infinite — so it is **not** a dark-matter candidate:
    the carrier is the cell singlet B (cl10/cell.py), whose portal strength is
    the open number (O7)."""
    x = np.linspace(-30, 30, 20001)
    dx = x[1] - x[0]
    u = np.sqrt(2.0) / np.cosh(x)
    # the exact solution of u'' = u - u^3 (4th-order central 2nd difference)
    u2 = (-np.roll(u, 2) + 16.0 * np.roll(u, 1) - 30.0 * u + 16.0 * np.roll(u, -1)
          - np.roll(u, -2)) / (12.0 * dx ** 2)
    ode_res = float(np.max(np.abs(u2[4:-4] - (u - u ** 3)[4:-4])))
    # the kink energy:  int [ 1/2 (u')^2 + V(u) ] dx  (per unit area in 3-D)
    up = (np.roll(u, 1) - np.roll(u, -1)) / (2.0 * dx)
    V = 0.5 * u ** 2 - 0.25 * u ** 4
    kink_energy = float(np.trapezoid(0.5 * up ** 2 + V, x))
    # the non-dispersive bound state (the sech tail -> the vacuum)
    tail = float(np.max(np.abs(u[[0, 1, 2, -1, -2, -3]])))
    localized = bool(tail < _TOL.loose and 0.0 < kink_energy < 10.0)
    return {
        "backend": _backend(),
        "ode_residual": ode_res,
        "mass_energy_E": kink_energy,
        "non_dispersive": localized,
        "gauge_charge": 0.0,
        "stable_massive_non_dispersive_neutral": bool(
            ode_res < _TOL.loose and localized and kink_energy > 0.0),
    }


